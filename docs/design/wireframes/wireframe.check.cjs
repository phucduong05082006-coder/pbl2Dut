const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');

const html = fs.readFileSync(require('node:path').join(__dirname, 'wireframe.html'), 'utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
const context = vm.createContext({ Intl, assert });
vm.runInContext(script, context);
vm.runInContext(`
  state.session = 'U002';
  assert.equal(soldSeats('SC001').length, 7);
  const transactionCount = state.transactions.length;
  const ticketCount = state.tickets.length;
  assert.throws(() => completeSale('SC001', ['B01'], false), /xác nhận/);
  assert.throws(() => completeSale('SC001', [], true), /ít nhất/);
  assert.throws(() => completeSale('SC001', ['B01','B01'], true), /trùng/);
  assert.throws(() => completeSale('SC001', ['A01'], true), /đã bán/);
  assert.throws(() => completeSale('SC001', ['Z99'], true), /không thuộc/);
  assert.throws(() => completeSale('SC005', ['B01'], true), /không còn/);
  assert.throws(() => completeSale('SC006', ['B01'], true), /đã bắt đầu/);
  assert.equal(state.transactions.length, transactionCount);
  assert.equal(state.tickets.length, ticketCount);
  const transaction = completeSale('SC001', ['B01','B02'], true);
  assert.equal(transaction.total, 160000);
  assert.equal(state.transactions.length, transactionCount+1);
  assert.equal(state.tickets.length, ticketCount+2);
  assert.equal(soldSeats('SC001').length, 9);
  assert.throws(() => completeSale('SC001', ['B01'], true), /đã bán/);
  completeSale('SC002', ['B01'], true);
  assert.equal(reportData().revenue, 800000);
  assert.equal(reportData().tickets.length, 10);
  state.users[1].canSell = false;
  assert.throws(() => completeSale('SC002', ['B02'], true), /quyền/);
  assert.throws(() => validateSchedule({}), /quản lý/);
  state.session = null;
  assert.throws(() => completeSale('SC002', ['B02'], true), /quyền/);
  state.session = 'U001';
  const candidate = { filmId:'F001', roomId:'R001', price:80000, start:'2026-10-11T13:22:00+07:00' };
  assert.throws(() => validateSchedule(candidate), /trùng/);
  candidate.start = '2026-10-11T16:55:00+07:00';
  assert.equal(validateSchedule(candidate).duration, 98);
  assert.equal(new Set(state.tickets.map(ticket => ticket.id)).size, state.tickets.length);
  state.reportFrom = '2026-10-12';
  state.reportTo = '2026-10-12';
  assert.equal(reportData().revenue, 0);
  state.reportTo = '2026-10-11';
  assert.throws(() => reportData(), /Ngày bắt đầu/);
  assert.equal(escapeHtml('<img src=x onerror="alert(1)">'), '&lt;img src=x onerror=&quot;alert(1)&quot;&gt;');
`, context);
assert.equal(/(?:href|src)=["']https?:\/\//.test(html), false, 'Wireframe must not load external resources');
console.log('PASS: wireframe sale, validation, permissions, reporting, schedule boundaries, unique IDs, escaping and offline resources.');
